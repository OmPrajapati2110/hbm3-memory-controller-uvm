#!/usr/bin/env python3
"""Collect regression, coverage, bug-injection, formal, policy-sweep and
synthesis results into docs/results.md and the results table in README.md."""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
R = os.path.join(ROOT, "results")


def load(name):
    p = os.path.join(R, name)
    return json.load(open(p)) if os.path.exists(p) else None


def formal_status():
    out = {}
    fdir = os.path.join(ROOT, "formal")
    for d in sorted(os.listdir(fdir)):
        st = os.path.join(fdir, d, "status")
        if d.startswith("hbm3_mc_") and os.path.isfile(st):
            out[d[len("hbm3_mc_"):]] = open(st).read().split()[0]
    return out


def synth_stats():
    p = os.path.join(ROOT, "syn", "stat.txt")
    if not os.path.exists(p):
        return None
    s = open(p).read()
    cells = re.findall(r"Number of cells:\s+(\d+)", s)
    ffs = sum(int(n) for n in re.findall(r"\$_(?:S?DFFE?|ALDFFE?|DFFSRE?)_\w+\s+(\d+)", s))
    return {"cells": int(cells[-1]) if cells else 0, "flops": ffs}


def main():
    reg = load("regression.json")
    mut = load("mutants.json")
    sweep = load("policy_sweep.json")
    fs = formal_status()
    syn = synth_stats()
    s = reg["summary"] if reg else None

    rows = []
    if s:
        rows.append(("Seeded regression", f"{s['passed']}/{s['runs']} runs pass, "
                     f"{s['requests_checked']:,} requests checked end to end"))
        fc, ac = s["functional_coverage"], s["assertion_coverage"]
        rows.append(("Functional coverage", f"{fc['pct']}% ({fc['hit']}/{fc['total']} bins)"))
        rows.append(("Assertion cover properties", f"{ac['pct']}% ({ac['hit']}/{ac['total']}), "
                     "every timing rule hit exactly at its limit"))
    if mut:
        k = sum(m["killed"] for m in mut)
        rows.append(("Bug injection", f"{k}/{len(mut)} injected bugs caught"))
    if fs:
        ok = fs.get("bmc") == "PASS"
        muts = [k for k in fs if k.startswith("mut_")]
        caught = sum(fs[k] == "FAIL" for k in muts)
        rows.append(("Formal (SymbiYosys BMC, depth 40)",
                     f"{'all 43 assertions proven' if ok else 'FAILED'}; "
                     f"{caught}/{len(muts)} formal mutants caught"))
    rows.append(("SV UVM bench", "elaborates with 0 errors against Accellera UVM 2020 (slang)"))
    if syn:
        rows.append(("Synthesis (Yosys, generic gates)", f"{syn['cells']:,} cells, {syn['flops']:,} flip-flops"))
    if sweep:
        a = sweep.get("test_starvation/FR-FCFS+aging", {})
        b = sweep.get("test_starvation/FR-FCFS", {})
        if a and b:
            rows.append(("Starvation (victim worst latency)",
                         f"FR-FCFS {b['worst']:,} cycles vs aging {a['worst']:,} cycles"))

    table = ["| Metric | Result |", "|---|---|"] + [f"| {a} | {b} |" for a, b in rows]

    readme = os.path.join(ROOT, "README.md")
    txt = open(readme).read()
    txt = re.sub(r"<!-- RESULTS:BEGIN -->.*<!-- RESULTS:END -->",
                 "<!-- RESULTS:BEGIN -->\n" + "\n".join(table) + "\n<!-- RESULTS:END -->",
                 txt, flags=re.S)
    open(readme, "w").write(txt)

    L = ["# Results", "", "Generated by `scripts/make_report.py` from the files in `results/`.", ""]
    L += table + [""]
    if os.path.exists(os.path.join(R, "regression.md")):
        L += ["## Regression and coverage", ""]
        L += open(os.path.join(R, "regression.md")).read().split("\n")[1:]
    if os.path.exists(os.path.join(R, "mutants.md")):
        L += ["## Bug injection", ""] + open(os.path.join(R, "mutants.md")).read().split("\n")[1:]
    if fs:
        L += ["## Formal", "", "| Task | Expected | Result |", "|---|---|---|"]
        for k, v in fs.items():
            L.append(f"| {k} | {'PASS' if k == 'bmc' else 'FAIL (mutant)'} | {v} |")
        L.append("")
    if os.path.exists(os.path.join(R, "policy_sweep.md")):
        L += ["## Scheduling policy comparison", ""]
        L += open(os.path.join(R, "policy_sweep.md")).read().split("\n")[1:]
    extra = os.path.join(ROOT, "docs", "bugs_found.md")
    if os.path.exists(extra):
        L += open(extra).read().split("\n")
    open(os.path.join(ROOT, "docs", "results.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(table))


if __name__ == "__main__":
    main()
